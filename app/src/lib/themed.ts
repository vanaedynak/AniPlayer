// Themed achievements: one anime followed episode by episode, like the old Jut.su did.
// A step counts episodes watched across all the anime's MAL ids (n), or the furthest episode reached
// in the first one (ep: «дойти до 25 серии»). The numbers come from Stats.mal_eps.
import type { Achievement, Rarity, Stats } from './achievements'

type Step = [kind: 'n' | 'ep', goal: number, icon: string, label: string, rarity: Rarity, about?: string]

const watchedIn = (s: Stats, ids: number[]) => ids.reduce((n, id) => n + (s.mal_eps?.[id]?.[0] ?? 0), 0)
const reachedIn = (s: Stats, id: number) => s.mal_eps?.[id]?.[1] ?? 0

const themed = (key: string, title: string, ids: number[], blurb: string, steps: Step[]): Achievement[] =>
  steps.map(([kind, goal, icon, label, rarity, about]) => ({
    id: `t-${key}-${kind}${goal}`,
    category: 'theme',
    icon,
    label,
    hint: kind === 'ep' ? `Дойти до ${goal} серии «${title}»` : goal === 1 ? `Посмотреть первую серию «${title}»` : `Посмотреть ${goal} серий «${title}»`,
    rarity,
    goal,
    value: kind === 'ep' ? (s) => reachedIn(s, ids[0]) : (s) => watchedIn(s, ids),
    about: about ?? (goal === 1 ? `С этого всё начинается. ${blurb}` : blurb),
    anime: title,
  }))

